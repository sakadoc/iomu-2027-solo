  const sourceFiles = ['BUKA_WEBSITE_IOMU2027.html', path.join('public', 'app-3d-bundle.js')];
  const tokens = new Set();

  for (const relPath of sourceFiles) {
    const fullPath = path.join(rootDir, relPath);
    if (!fs.existsSync(fullPath)) continue;
    const txt = fs.readFileSync(fullPath, 'utf8');

    const attrRe = /\bclass(?:Name)?\s*=\s*(?:"([^"]*)"|'([^']*)'|`([^`]*)`)/g;
    let m;
    while ((m = attrRe.exec(txt))) {
      const raw = (m[1] ?? m[2] ?? m[3] ?? '').replace(/\$\{[^}]*\}/g, ' ');
      raw.split(/\s+/).filter(Boolean).forEach((c) => tokens.add(c));
    }

    const strRe = /['"`]([a-z0-9\-:\[\]\/\.%]+(?:\s+[a-z0-9\-:\[\]\/\.%]+)+)['"`]/gi;
    while ((m = strRe.exec(txt))) {
      const s = m[1];
      if (/(?:rounded-|border-|bg-|text-|px-|py-|flex|grid|hidden|fixed|inline-flex)/.test(s)) {
        s.replace(/\$\{[^}]*\}/g, ' ')
          .split(/\s+/)
          .filter(Boolean)
          .forEach((c) => {
            if (/^[a-z0-9\-:\[\]\/\.%]+$/i.test(c) && !c.includes('://')) {
              tokens.add(c);
            }
          });
      }
    }
  }

