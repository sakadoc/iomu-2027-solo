/**
 * Compiles all Tailwind CSS utility classes used in BUKA_WEBSITE_IOMU2027.html
 * and public/app-3d-bundle.js into a static stylesheet so Microsoft Edge,
 * Chrome, and offline/proxied browsers never depend on cdn.tailwindcss.com.
 */
