import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const brandDir = path.join(rootDir, 'public', 'assets', 'brand');
const distDir = path.join(rootDir, 'dist');
const distBrandDir = path.join(distDir, 'assets', 'brand');

fs.mkdirSync(distBrandDir, { recursive: true });

const assetKeys = {
  logoDarkBg: 'logo-iomu-dark.png',
  logoLightBg: 'logo-iomu-light.png',
  logoMonoGold: 'logo-iomu-mono-gold.png',
  logoMonoWhite: 'logo-iomu-mono-white.png',
  logoEmblem: 'logo-iomu-emblem.png',
  logoPerdoki: 'logo-perdoki.png',
  logoIdi: 'logo-idi.png',
  kawungGold: 'pola-kawung-emas.png',
  kawungGreen: 'pola-kawung-hijau.png',
  gununganGold: 'gunungan-emas.png',
  skylineCream: 'skyline-solo-cream.png',
  panggungSanggaBuwanaPhoto: 'landmark-panggung-sangga-buwana.png',
  delegates2026OverlayPhoto: 'foto-peserta-2026-overlay.jpg',
  delegates2026RawPhoto: 'foto-peserta-2026.jpg',
  pinGoldIcon: 'icon-pin-emas.png',
};

const bundle = {};

for (const [key, filename] of Object.entries(assetKeys)) {
  const filePath = path.join(brandDir, filename);
  if (!fs.existsSync(filePath)) {
    throw new Error(`Missing brand asset: ${filePath}`);
  }
  const ext = path.extname(filename).toLowerCase();
  const mime = ext === '.jpg' || ext === '.jpeg' ? 'image/jpeg' : 'image/png';
  const base64 = fs.readFileSync(filePath).toString('base64');
  bundle[key] = `data:${mime};base64,${base64}`;
  fs.copyFileSync(filePath, path.join(distBrandDir, filename));
}

const brandJsContent = `// Auto-generated by scripts/build-standalone.mjs for CORS-free file:// and WebGL textures\nwindow.IOMU_BRAND_ASSETS = ${JSON.stringify(bundle)};\n`;
fs.writeFileSync(path.join(brandDir, 'brand-assets.js'), brandJsContent, 'utf8');
fs.writeFileSync(path.join(distBrandDir, 'brand-assets.js'), brandJsContent, 'utf8');

const appBundleSrc = path.join(rootDir, 'public', 'app-3d-bundle.js');
if (fs.existsSync(appBundleSrc)) {
  fs.copyFileSync(appBundleSrc, path.join(distDir, 'app-3d-bundle.js'));
}

const rootLauncher = path.join(rootDir, 'BUKA_WEBSITE_IOMU2027.html');
if (fs.existsSync(rootLauncher)) {
  // dist/index.html uses relative ./app-3d-bundle.js and ./assets/brand/brand-assets.js
  const html = fs.readFileSync(rootLauncher, 'utf8')
    .replaceAll('./public/assets/brand/brand-assets.js', './assets/brand/brand-assets.js')
    .replaceAll('./public/app-3d-bundle.js', './app-3d-bundle.js');
  fs.writeFileSync(path.join(distDir, 'index.html'), html, 'utf8');
}

fs.writeFileSync(path.join(distDir, '_redirects'), '/* /index.html 200\n', 'utf8');

console.log(`Generated brand-assets.js (${Object.keys(bundle).length} assets) and synced dist/.`);
